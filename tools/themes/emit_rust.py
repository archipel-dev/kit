"""Writes the generated Rust modules (crates/archipel-kit/src/theme/generated/)."""

import json

HEADER = "// @generated by tools/themes — do not edit\n"


def lit_str(text):
    return json.dumps(text, ensure_ascii=True)


def lit_color(value):
    return f"0x{value:08X}"


def lit_opt(value):
    return "None" if value is None else f"Some({lit_color(value)})"


def lit_float(value):
    text = repr(float(value))
    return text


def provenance(meta):
    return (
        f"// Source: IntelliJ Community {meta['tag']} ({meta['commit']}), Apache-2.0.\n"
        "// Only color and metric values are taken; see NOTICE.md.\n"
    )


def emit_ui(theme, resolved, mapped, meta):
    """One UI theme: its tables and the function that fills `Colors`."""
    out = [HEADER, provenance(meta)]
    out.append(f"//! {theme['name']}: resolved from {' -> '.join(c[1].split('/')[-1] for c in resolved.chain)}.\n\n")
    out.append("use super::super::Colors;\n")
    out.append("use super::super::catalog::{UiData, px};\n\n")
    out.append("pub(in crate::theme) static DATA: UiData = UiData {\n")
    out.append(f"    id: {lit_str(theme['id'])},\n")
    out.append(f"    name: {lit_str(theme['name'])},\n")
    out.append(f"    dark: {'true' if resolved.dark else 'false'},\n")
    out.append(f"    scheme: {lit_str(theme['scheme_id'])},\n")
    out.append("    chain: &[\n")
    for provider, _ in resolved.chain:
        out.append(f"        {lit_str(provider)},\n")
    out.append("    ],\n    colors: &[\n")
    for key in sorted(resolved.colors):
        out.append(f"        ({lit_str(key)}, {lit_color(resolved.colors[key])}),\n")
    out.append("    ],\n    numbers: &[\n")
    for key in sorted(resolved.numbers):
        out.append(f"        ({lit_str(key)}, {lit_float(resolved.numbers[key])}),\n")
    out.append("    ],\n    flags: &[\n")
    for key in sorted(resolved.flags):
        out.append(f"        ({lit_str(key)}, {'true' if resolved.flags[key] else 'false'}),\n")
    out.append("    ],\n    strings: &[\n")
    for key in sorted(resolved.strings):
        out.append(f"        ({lit_str(key)}, {lit_str(resolved.strings[key])}),\n")
    out.append("    ],\n};\n\n")
    out.append("/// Fills the workbench colors from the UI theme; unmapped fields keep `c`'s value.\n")
    out.append("pub(in crate::theme) fn colors(mut c: Colors) -> Colors {\n")
    kept = []
