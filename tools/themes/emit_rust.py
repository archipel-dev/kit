def emit_scheme(spec, scheme, parent_id, dark, mapped, meta):
    """One editor scheme: own colors and attributes, and the `EditorColors` filler."""
    out = [HEADER, provenance(meta)]
    out.append(f"//! Editor color scheme {spec['name']}.\n\n")
    out.append("use super::super::EditorColors;\n")
    out.append("use super::super::catalog::{Attr, SchemeData, px};\n")
    if parent_id:
        out.append(f"use super::scheme_{parent_id};\n")
    out.append("\npub(in crate::theme) static DATA: SchemeData = SchemeData {\n")
    out.append(f"    id: {lit_str(spec['id'])},\n")
    out.append(f"    name: {lit_str(spec['name'])},\n")
    out.append(f"    dark: {'true' if dark else 'false'},\n")
    out.append(f"    parent: {f'Some(&scheme_{parent_id}::DATA)' if parent_id else 'None'},\n")
    out.append("    colors: &[\n")
    for name in sorted(scheme.colors):
        out.append(f"        ({lit_str(name)}, {lit_opt(scheme.colors[name])}),\n")
    out.append("    ],\n    attributes: &[\n")
    for name in sorted(scheme.attributes):
        a = scheme.attributes[name]
        if a["effect_type"] is None and a["effect_color"] is None:
            effect = "None"
        else:
            effect = f"Some(({a['effect_type'] or 0}, {lit_opt(a['effect_color'])}))"
        base = "None" if not a["base"] else f"Some({lit_str(a['base'])})"
        out.append(
            f"        Attr {{ name: {lit_str(name)}, fg: {lit_opt(a['fg'])}, bg: {lit_opt(a['bg'])}, "
            f"font: {a['font']}, effect: {effect}, stripe: {lit_opt(a['stripe'])}, base: {base} }},\n"
        )
    out.append("    ],\n    editor,\n};\n\n")
    out.append("/// Fills the editor colors from the scheme; unmapped fields keep `e`'s value.\n")
    out.append("fn editor(mut e: EditorColors) -> EditorColors {\n")
    kept = []
    for field, (value, label) in mapped.items():
        if value is None:
            kept.append(field)
            continue
        out.append(f"    e.{field} = px({lit_color(value)}); // {label}\n")
    if kept:
        out.append(f"    // Kept at the measured value: {', '.join(kept)}.\n")
    out.append("    e\n}\n")
    return "".join(out)


def emit_index(ui_themes, scheme_specs, meta):
    out = [HEADER, provenance(meta)]
    out.append("//! The bundled themes and schemes: registries and the `Theme` constructors.\n\n")
    for scheme in scheme_specs:
        out.append(f"mod scheme_{scheme['id']};\n")
    for theme in ui_themes:
        out.append(f"mod ui_{theme['id']};\n")
    out.append("\nuse super::Theme;\n")
    out.append("use super::catalog::{EditorScheme, ThemeInfo, UiEntry, build};\n")
    out.append("use crate::look::UiLook;\n\n")
    out.append("pub(super) static UI: &[UiEntry] = &[\n")
    for theme in ui_themes:
        out.append(
            f"    UiEntry {{ data: &ui_{theme['id']}::DATA, colors: ui_{theme['id']}::colors }},\n"
        )
    out.append("];\n\n")
    out.append("pub(super) static SCHEMES: &[EditorScheme] = &[\n")
    for scheme in scheme_specs:
        out.append(f"    EditorScheme(&scheme_{scheme['id']}::DATA),\n")
    out.append("];\n\n")
    out.append("pub(super) static THEMES: &[ThemeInfo] = &[\n")
    entries = [
        ("archipel_dark", "Archipel Dark", True, "dark", "Islands"),
        ("archipel_light", "Archipel Light", False, "light", "Islands"),
    ]
    for theme in ui_themes:
        entries.append((theme["id"], theme["name"], theme["dark"], theme["ctor"], theme["look"]))
    for ident, name, dark, ctor, look in entries:
        out.append(
            f"    ThemeInfo {{ id: {lit_str(ident)}, name: {lit_str(name)}, "
            f"dark: {'true' if dark else 'false'}, constructor: Theme::{ctor}, look: UiLook::{look} }},\n"
        )
    out.append("];\n\nimpl Theme {\n")
    for theme in ui_themes:
        out.append(
            f"    /// {theme['name']}: the bundled IntelliJ Community theme "
            f"({'dark' if theme['dark'] else 'light'}) with its editor scheme.\n"
            f"    pub fn {theme['ctor']}() -> Self {{\n"
            f"        build({lit_str(theme['id'])})\n    }}\n\n"
        )
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)
