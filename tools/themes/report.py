"""Writes docs/theme-mapping.md: the mapping, what fell back, and the validation against the
kit's hand-measured Islands palettes."""

from mapping import COLORS, EDITOR, GEOMETRY_KEYS


def hexc(value):
    if value is None:
        return "-"
    rgb = f"#{value >> 8:06X}"
    return rgb if value & 0xFF == 0xFF else f"{rgb}/{value & 0xFF:02X}"


def delta(a, b):
    """Largest channel difference (RGBA) between two packed colors."""
    return max(abs(((a >> s) & 0xFF) - ((b >> s) & 0xFF)) for s in (24, 16, 8, 0))


def verdict(a, b):
    d = delta(a, b)
    if d == 0:
        return "exact"
    if d <= 8:
        return f"near ({d})"
    return f"differs ({d})"


def mapping_table(entries, kind):
    rows = ["| Kit field | IntelliJ source (first that resolves wins) |", "|---|---|"]
    for field, sources in entries:
        text = ", ".join(f"`{s}`" for s in sources) if sources else "_no IntelliJ key: measured value_"
        rows.append(f"| `{field}` | {text} |")
    return "\n".join(rows)


def validation(title, generated, measured, labels, only_diff=False):
    rows = [
        f"| Field | Measured (`{title[0]}`) | Generated (`{title[1]}`) | Verdict | Source |",
        "|---|---|---|---|---|",
    ]
    counts = {"exact": 0, "near": 0, "differs": 0, "kept": 0, "unmeasured": 0}
    for field, value in generated.items():
        m = measured.get(field)
        if value is None:
            counts["kept"] += 1
            rows.append(f"| `{field}` | {hexc(m)} | _kept (no key)_ | measured value | - |")
            continue
        if m is None:
            counts["unmeasured"] += 1
            rows.append(f"| `{field}` | - | {hexc(value)} | - | {labels[field]} |")
            continue
        v = verdict(value, m)
        counts[v.split(" ")[0]] += 1
        if only_diff and v == "exact":
            continue
        rows.append(f"| `{field}` | {hexc(m)} | {hexc(value)} | {v} | `{labels[field]}` |")
    return counts, "\n".join(rows)


def build(meta, themes, schemes, measured, unmapped, checks):
    """`themes`: list of dict(spec, resolved, mapped); `schemes`: list of dict(spec, mapped,
    dark, parent_id, scheme); `checks`: [(title, measured_key, theme_id)]."""
    out = []
    w = out.append
    w("<!-- @generated by tools/themes — do not edit -->")
    w("# Theme mapping\n")
    w(
        f"Generated from the data files of IntelliJ Community `{meta['tag']}` (commit "
        f"`{meta['commit']}`, Apache-2.0; see [`NOTICE.md`](../NOTICE.md)) by "
        "[`tools/themes`](../tools/themes/README.md). Regenerate with "
        "`python3 -I tools/themes/generate.py --community PATH --tag TAG`. The table below is "
        "`tools/themes/mapping.py`.\n"
    )
    w("## Shipped themes\n")
    w("| Theme | `Theme::` | IntelliJ theme chain | Editor scheme | UI keys | Colors from IntelliJ | Kept measured |")
    w("|---|---|---|---|---|---|---|")
    for t in themes:
        r = t["resolved"]
        mapped = t["mapped"]
        kept = [f for f, (v, _) in mapped.items() if v is None]
        total = len(mapped)
        chain = " → ".join(p for p, _ in r.chain)
        n_keys = len(r.colors) + len(r.numbers) + len(r.flags) + len(r.strings)
        w(
            f"| {t['spec']['name']} | `{t['spec']['ctor']}()` | {chain} | {t['scheme_name']} | {n_keys} | "
            f"{total - len(kept)} / {total} | {len(kept)} |"
        )
    w("\n## Editor schemes\n")
    w("| Scheme | Id | Inherits | Own colors | Own attributes | Fields from the scheme | Kept measured |")
    w("|---|---|---|---|---|---|---|")
    for s in schemes:
        mapped = s["mapped"]
        kept = [f for f, (v, _) in mapped.items() if v is None]
        w(
            f"| {s['spec']['name']} | `{s['spec']['id']}` | {s['parent_name'] or '-'} | "
            f"{len(s['scheme'].colors)} | {len(s['scheme'].attributes)} | "
            f"{len(mapped) - len(kept)} / {len(mapped)} | {len(kept)} |"
        )
    w("\n## Mapping: workbench `Colors`\n")
    w(mapping_table(COLORS, "colors"))
    w("\nSource syntax is documented at the top of `tools/themes/mapping.py`.\n")
    w("## Mapping: `EditorColors`\n")
    w(mapping_table(EDITOR, "editor"))
    if unmapped:
        w("\n## Fields without a mapping\n")
        w("Kit fields that `mapping.py` does not list keep the measured value in every theme: " + ", ".join(f"`{f}`" for f in unmapped) + ".")
    w("\n## Fields that fell back to the measured values\n")
    w("Where no IntelliJ key resolves, the field keeps the kit's measured value (`Theme::dark()` for dark themes, `Theme::light()` for light ones).\n")
    w("| Theme | `Colors` fields kept |")
    w("|---|---|")
    for t in themes:
        kept = [f for f, (v, _) in t["mapped"].items() if v is None]
        w(f"| {t['spec']['name']} | {', '.join(f'`{f}`' for f in kept) or '-'} |")
    w("\n| Scheme | `EditorColors` fields kept |")
    w("|---|---|")
    for s in schemes:
        kept = [f for f, (v, _) in s["mapped"].items() if v is None]
        w(f"| {s['spec']['name']} | {', '.join(f'`{f}`' for f in kept) or '-'} |")
    w("\n## Validation against the measured palettes\n")
    w(
        "`Theme::dark()` and `Theme::light()` were measured on the running IDE. The generated "
        "Islands themes must land on the same values; `exact` is identical, `near` differs by "
        "at most 8 in one channel, `differs` is a real difference (a different token or a "
        "kit-specific tweak). The generated values never replace the measured ones.\n"
    )
    for title, measured_key, theme_id in checks:
        t = next(t for t in themes if t["spec"]["id"] == theme_id)
        generated = {f: v for f, (v, _) in t["mapped"].items()}
        labels = {f: l for f, (_, l) in t["mapped"].items()}
        counts, table = validation(title, generated, measured[measured_key]["colors"], labels)
        w(f"### `Colors`: {title[1]} vs {title[0]}\n")
        w(
            f"exact {counts['exact']}, near {counts['near']}, differs {counts['differs']}, "
            f"kept (no key) {counts['kept']}.\n"
        )
        w(table + "\n")
        s = next(s for s in schemes if s["spec"]["id"] == t["scheme_id"])
        generated = {f: v for f, (v, _) in s["mapped"].items()}
        labels = {f: l for f, (_, l) in s["mapped"].items()}
        counts, table = validation(
            (title[0] + " editor", title[1] + " + scheme " + s["spec"]["name"]),
            generated,
            measured[measured_key]["editor"],
            labels,
        )
        w(f"### `EditorColors`: {title[1]} vs {title[0]}\n")
        w(
            f"exact {counts['exact']}, near {counts['near']}, differs {counts['differs']}, "
            f"kept (no key) {counts['kept']}.\n"
        )
        w(table + "\n")
    w("## Geometry\n")
    w(
        "Every theme's numeric and size keys are in its generated table "
        "(`Theme::ui_number`, `ui_insets`, `ui_size`). Component geometry follows the Islands look "
        "for all themes for now; these are the keys each theme file sets (`-` when the theme "
        "does not).\n"
    )
    head = "| Key | " + " | ".join(t["spec"]["name"] for t in themes) + " |"
    w(head)
    w("|---|" + "---|" * len(themes))
    for key in GEOMETRY_KEYS:
        cells = []
        for t in themes:
            r = t["resolved"]
            value = r.numbers.get(key, r.strings.get(key))
            cells.append("-" if value is None else (f"{value:g}" if isinstance(value, (int, float)) else str(value)))
        w(f"| `{key}` | " + " | ".join(cells) + " |")
    w("\n## Values the theme files reference but do not define\n")
    w(
        "Strings that are neither a color, a number, an icon, a class nor another key. They live "
        "in the base look and feel (Java code) or name a UIManager key; they are not in the "
        "tables.\n"
    )
    w("| Theme | Keys |")
    w("|---|---|")
    for t in themes:
        r = t["resolved"]
        keys = ", ".join(f"`{k}` = `{v}`" for k, v in sorted(r.unresolved.items()))
        w(f"| {t['spec']['name']} | {keys or '-'} |")
    return "\n".join(out) + "\n"


def validation_block(themes, schemes, measured, checks):
    """The markdown embedded in docs/theming.md: per pair the counts and the rows that are
    not exact."""
    out = []
    for title, measured_key, theme_id in checks:
        t = next(t for t in themes if t["spec"]["id"] == theme_id)
        generated = {f: v for f, (v, _) in t["mapped"].items()}
        labels = {f: l for f, (_, l) in t["mapped"].items()}
        counts, table = validation(title, generated, measured[measured_key]["colors"], labels, True)
        out.append(f"**`Colors`, `{title[1]}` vs `{title[0]}`:** {counts['exact']} exact, {counts['near']} near, {counts['differs']} differ, {counts['kept']} kept (no IntelliJ key).\n")
        out.append(table + "\n")
        s = next(s for s in schemes if s["spec"]["id"] == t["scheme_id"])
        generated = {f: v for f, (v, _) in s["mapped"].items()}
        labels = {f: l for f, (_, l) in s["mapped"].items()}
        counts, table = validation(
            (title[0] + " editor", title[1] + " + " + s["spec"]["name"]),
            generated,
            measured[measured_key]["editor"],
            labels,
            True,
        )
        out.append(f"**`EditorColors`, `{title[1]}` with scheme {s['spec']['name']} vs `{title[0]}`:** {counts['exact']} exact, {counts['near']} near, {counts['differs']} differ, {counts['kept']} kept.\n")
        out.append(table + "\n")
    return "\n".join(out)
