/// Origins (top-left of each cell) that center a label of `count` letters on `center`.
pub fn origins(count: usize, center: Point) -> impl Iterator<Item = Point> {
    // Stroke centers span WIDTH - 1 per letter, plus GAP + 1 between letters.
    let span = count as f32 * (WIDTH - 1.0) + count.saturating_sub(1) as f32 * (GAP + 1.0);
    let left = center.0 - span / 2.0;
    let top = center.1 - (HEIGHT - 1.0) / 2.0;
    (0..count).map(move |i| (left + i as f32 * (WIDTH + GAP), top))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_stay_in_their_cell() {
        for letter in ('A'..='Z').chain("+#{}<>@".chars()) {
            let strokes = strokes(letter).unwrap_or_else(|| panic!("missing {letter}"));
            for &(x, y) in strokes.iter().flat_map(|s| s.iter()) {
                assert!(
                    (0.0..=3.0).contains(&x) && (0.0..=5.0).contains(&y),
                    "{letter}: ({x}, {y})"
                );
            }
        }
    }

    #[test]
    fn two_letters_center_in_a_tile() {
        let cells: Vec<Point> = origins(2, (8.0, 8.0)).collect();
        assert_eq!(cells, vec![(3.5, 5.5), (9.5, 5.5)]);
        // Strokes span 3.5..12.5: centered on 8.
        assert_eq!(origins(1, (8.0, 8.0)).next(), Some((6.5, 5.5)));
    }
}
