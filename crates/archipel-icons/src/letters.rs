//! A tiny stroke font for icon labels: capital letters and a few symbols, each a set of
//! polylines in a 4×6 cell (stroke centers on x 0..3, y 0..5). At 16 px a letter is four
//! pixels wide and six tall; two letters with a two-unit gap are ten units wide, so a label
//! centers exactly in a 16-unit tile.

use crate::Point;

/// Cell width in grid units (stroke centers span 0..3, plus half a stroke on each side).
pub const WIDTH: f32 = 4.0;
/// Cell height in grid units.
pub const HEIGHT: f32 = 6.0;
/// Gap between the cells of a two-letter label.
pub const GAP: f32 = 2.0;

type Strokes = &'static [&'static [Point]];

